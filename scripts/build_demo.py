#!/usr/bin/env python3
"""Bundle the local preview; the shared server serves the same module sources.

Only local, named ESM imports/re-exports are supported. No network module loader,
external dependencies or opaque-preview module permissions are required.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
IMPORT = re.compile(r"^import\s*\{([^}]+)\}\s*from\s*['\"]([^'\"]+)['\"];?", re.M)
REEXPORT = re.compile(r"^export\s*\*\s*from\s*['\"]([^'\"]+)['\"];?", re.M)
EXPORT = re.compile(r"^export\s+(?:(?:async\s+)?function|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)


def bundle(entry):
    modules = {}
    def visit(path):
        path = path.resolve()
        if not path.is_relative_to(ROOT):
            raise ValueError('Module outside workspace project')
        key = path.relative_to(ROOT).as_posix()
        if key in modules:
            return key
        modules[key] = ''
        source = path.read_text(encoding='utf-8')
        def dependency(spec):
            if not spec.startswith('.'):
                raise ValueError('Only local modules supported: '+spec)
            return visit(path.parent / spec)
        def replace_import(match):
            dep = dependency(match[2])
            names = match[1].strip()
            if not re.fullmatch(r'[\w\s,$]+', names):
                raise ValueError('Only simple named imports supported: '+names)
            return f'const {{ {names} }} = __require({dep!r});'
        source = IMPORT.sub(replace_import, source)
        source = REEXPORT.sub(lambda m: f'Object.assign(__exports,__require({dependency(m[1])!r}));', source)
        names = EXPORT.findall(source)
        source = re.sub(r'^export\s+(?=(?:async\s+)?function|const|let|class)', '', source, flags=re.M)
        if re.search(r'^\s*(?:import|export)\b|\bimport\s*\(', source, re.M):
            raise ValueError('Unsupported module syntax in '+key)
        modules[key] = source + '\nObject.assign(__exports, { '+', '.join(names)+' });\n'
        return key
    key = visit(entry)
    code = '(function(){"use strict";\nconst __modules = Object.create(null), __cache = Object.create(null);\n'
    for name, source in modules.items():
        code += f'__modules[{name!r}] = function(__exports, __require){{\n{source}\n}};\n'
    code += 'function __require(id){ if(__cache[id])return __cache[id]; const out=__cache[id]={}; __modules[id](out,__require); return out; }\n'
    return code + f'__require({key!r});\n}})();\n'


def build():
    demo = ROOT / 'demo'
    html = (demo / 'template.html').read_text(encoding='utf-8')
    css = (demo / 'style.css').read_text(encoding='utf-8')
    script = bundle(demo / 'app.mjs')
    css_tag = '<link rel="stylesheet" href="style.css">'
    script_tag = '<script type="module" src="app.mjs"></script>'
    if html.count(css_tag) != 1 or html.count(script_tag) != 1:
        raise ValueError('Expected single stylesheet and app script')
    html = html.replace(css_tag, '<style>\n'+css.replace('</style',r'<\/style')+'\n</style>')
    html = re.sub(r'(?m)^[ \t]*'+re.escape(script_tag)+r'\r?\n', '', html)
    html = html.replace('</body>', '<script>\n'+script.replace('</script',r'<\/script')+'\n</script>\n</body>')
    html = html.replace('<body>', '<body data-demo-build="foundations-v6">',1)
    html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build_demo.py; edit source files. Local preview, not a shared server. -->',1)
    for name in ['index.html','raktar-bemutato.html',*[f'raktar-bemutato-v{i}.html' for i in range(2,7)]]:
        (demo/name).write_text(html,encoding='utf-8')
    return demo/'raktar-bemutato-v6.html'

if __name__ == '__main__':
    print(build())
